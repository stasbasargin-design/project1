const assert = require('node:assert/strict');
const m = require('../exam-history.js');
const initial = new Date('2026-11-18T10:00:00Z');
const run = m.begin('exam_incoming', 17, initial);
assert.equal(run.totalSteps, 17);
m.markError(run); m.markError(run); m.markHint(run); m.completedStep(run, 17);
const good = m.finish(run, 'Завершён', new Date('2026-11-18T10:20:00Z'));
assert.equal(good.score, 88);
assert.equal(good.steps, 17);
assert.equal(good.outcome, 'Завершён');
const bad = m.finish(m.begin('exam_outgoing', 4, initial), 'Прерван');
assert.equal(bad.score, null);
const journal = m.append(m.append([], good), bad);
assert.equal(journal.length, 2);
assert.equal(journal[1].outcome, 'Прерван');
const csv = m.csv(journal, () => '=HYPERLINK("evil")');
assert.ok(csv.startsWith('\uFEFF'));
assert.ok(csv.includes("'=HYPERLINK"), 'CSV formula injection blocked');
assert.ok(csv.includes('88'));
const many = Array(610).fill(good).map((x, idx) => ({ ...x, id: String(idx) }));
assert.equal(m.normalizeAttempts(many).length, 500);
console.log('EXAM HISTORY OK: grading, interrupted attempts, CSV, limits');
