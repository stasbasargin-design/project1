  function finishExamAttempt(outcome) {
    if (!state.examRun) return null;
    // Не записываем пустую попытку: пользователь мог лишь открыть вкладку экзамена.
    if (outcome !== 'Завершён' && state.examRun.completedSteps === 0 && state.examRun.errors === 0 && state.examRun.hints === 0) {
      state.examRun = null;
      return null;
    }
    const result = examHistory.finish(state.examRun, outcome);
    state.examAttempts = examHistory.append(state.examAttempts, result);
    state.examRun = null;
    return result;
  }
