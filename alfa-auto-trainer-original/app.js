  function taskDateWithin60Days(value) {
    const match = String(value || '').trim().match(/^(\d{2})\.(\d{2})\.(\d{4})(?:\s+(\d{2}):(\d{2}))?$/);
    if (!match) return false;
    const [day, month, year, hours, minutes] = [Number(match[1]), Number(match[2]), Number(match[3]), Number(match[4] || 0), Number(match[5] || 0)];
    const selected = new Date(year, month - 1, day, hours, minutes);
    if (selected.getFullYear() !== year || selected.getMonth() !== month - 1 || selected.getDate() !== day || selected.getHours() !== hours || selected.getMinutes() !== minutes) return false;
    const today = new Date(); today.setHours(0, 0, 0, 0);
    const limit = new Date(today); limit.setDate(limit.getDate() + 60); limit.setHours(23, 59, 59, 999);
    return selected >= today && selected <= limit;
  }
  function crmTaskValidationMessage(task) {
    if (!String(task.responsible || '').trim()) return 'Выберите ответственного пользователя или группу.';
    if (!taskDateIsAllowed(task.dateStart)) return 'Дата начала задачи должна находиться в пределах месяца вперёд.';
    if (taskNeedsKoDates(task)) {
      if (task.generalQuestion) {
        if (!String(task.content || '').trim()) return 'При выборе «Общий вопрос» необходимо чётко заполнить поле «Содержание».';
      } else {
        if (!taskDateWithin60Days(task.dateProposed)) return 'Укажите корректную предлагаемую дату записи в пределах 60 календарных дней.';
        if (!taskDateWithin60Days(task.dateDesired)) return 'Укажите корректную желаемую дату записи в пределах 60 календарных дней.';
      }
    }
    return '';
  }

  function taskDateIsAllowed(value) {
    const match = String(value || '').match(/^(\d{2})\.(\d{2})\.(\d{4})/);
    if (!match) return false;
    const selected = new Date(Number(match[3]), Number(match[2]) - 1, Number(match[1]));
    const today = new Date(); today.setHours(0, 0, 0, 0);
    const limit = new Date(today); limit.setMonth(limit.getMonth() + 1);
    return selected >= today && selected <= limit;
  }

