  function applyRemoteState(remote, source = '1С') {
    if (!remote || typeof remote !== 'object') return false;
    if (remote.schemaVersion && remote.schemaVersion !== '1.0') {
      showToast(`Версия JSON ${remote.schemaVersion} не поддерживается приложением.`, 'warn');
      return false;
    }
    if (remote.directories && typeof remote.directories === 'object') {
      Object.keys(directoryMeta).forEach((type) => {
        if (Array.isArray(remote.directories[type])) state.directories[type] = clone(remote.directories[type]);
      });
    }
    if (remote.documents && typeof remote.documents === 'object') {
      Object.keys(state.documents).forEach((type) => {
        if (remote.documents[type] && typeof remote.documents[type] === 'object') state.documents[type] = Object.assign({}, state.documents[type], clone(remote.documents[type]));
      });
    }
    if (Array.isArray(remote.progress)) state.completed = new Set(remote.progress.filter((id) => trainingStages.some((stageItem) => stageItem.id === id)));
    if (Number.isFinite(Number(remote.revision))) state.revision = Math.max(state.revision, Number(remote.revision));
    state.documents.zn.parts = (state.documents.zn.parts || []).map(normalizePart);
    persist('remote.applied', { remote: true });
    render();
    showToast(`Данные обновлены из ${source}.`, 'success');
    return true;
  }

