  function saveDirectoryEditor() {
    const type = el.modal.dataset.directoryType;
    const id = el.modal.dataset.directoryId;
    const meta = directoryMeta[type];
    if (!meta) return;
    const values = {};
    let invalid = false;
    meta.fields.forEach(([key, , , required]) => {
      const input = el.modal.querySelector(`[data-dir-field="${key}"]`);
      values[key] = input.value.trim();
      if (required && !values[key]) { input.style.borderColor = '#d72e25'; invalid = true; }
    });
    if (invalid) { showToast('Заполните обязательные поля.', 'warn'); return; }
    if (id) {
      const index = state.directories[type].findIndex((row) => row.id === id);
      state.directories[type][index] = Object.assign({}, state.directories[type][index], values);
    } else {
      const newRow = Object.assign({ id: uid(type.slice(0, 1)), active: true }, values);
      state.directories[type].push(newRow);
      state.selected[type] = newRow.id;
    }
    persist();
    closeModal();
    render();
    showToast('Запись сохранена.', 'success');
  }

  function startInlineDirectoryEditor(type, id = '') {
    const meta = directoryMeta[type];
    const source = id ? state.directories[type].find((row) => row.id === id) : null;
    if (!meta || (id && !source)) return;
    const values = source ? clone(source) : {};
    if (!values.code) values.code = type === 'works' ? `АР-${String(state.directories[type].length + 1).padStart(6, '0')}` : type === 'parts' ? `ЗЧ-${String(state.directories[type].length + 1).padStart(6, '0')}` : '';
    state.directoryEditor = { type, id, values };
    render();
    setTimeout(() => { const first = el.screen.querySelector('[data-dir-inline-field="name"], [data-dir-inline-field]'); if (first) first.focus(); }, 0);
  }

  function saveInlineDirectoryEditor() {
    const editor = state.directoryEditor;
    if (!editor || !directoryMeta[editor.type]) return;
    const meta = directoryMeta[editor.type];
    const missing = meta.fields.find(([key, , , required]) => required && !String(editor.values[key] || '').trim());
    if (missing) {
      const input = el.screen.querySelector(`[data-dir-inline-field="${missing[0]}"]`);
      if (input) { input.classList.add('invalid'); input.focus(); }
      showToast(`Заполните обязательное поле «${missing[1]}».`, 'warn');
      return;
    }
    if (editor.id) {
      const index = state.directories[editor.type].findIndex((row) => row.id === editor.id);
      if (index >= 0) state.directories[editor.type][index] = Object.assign({}, state.directories[editor.type][index], clone(editor.values));
    } else {
      const newRow = Object.assign({ id: uid(editor.type.slice(0, 1)), active: true }, clone(editor.values));
      state.directories[editor.type].push(newRow);
      state.selected[editor.type] = newRow.id;
    }
    const type = editor.type;
    state.directoryEditor = null;
    persist(`directory.${type}.save`);
    notifyIntegration('directory.save', { directory: type, item: clone(editor.values), id: editor.id || '' });
    render();
    showToast('Элемент справочника записан.', 'success');
  }

  function directoryAction(action) {
    const type = state.activeObject;
    const selectedId = state.selected[type];
    const selected = state.directories[type] && state.directories[type].find((row) => row.id === selectedId);
    if (action === 'directory-add') { startInlineDirectoryEditor(type); return; }
    if (action === 'directory-cancel-inline') { state.directoryEditor = null; render(); return; }
    if (action === 'directory-save-inline') { saveInlineDirectoryEditor(); return; }
    if (action === 'directory-back') {
      const previous = state.returnTo ? state.returnTo.previous : 'desktop';
      state.activeObject = previous || 'desktop';
      state.returnTo = null;
      render();
      return;
    }
    if (!selected) { showToast('Сначала выберите строку справочника.', 'warn'); return; }
    if (action === 'directory-edit') { startInlineDirectoryEditor(type, selectedId); return; }
    if (action === 'directory-archive') {
      selected.active = selected.active === false;
      persist();
      render();
      showToast(selected.active ? 'Запись восстановлена.' : 'Запись перемещена в архив.', selected.active ? 'success' : 'warn');
      return;
    }
    if (action === 'directory-attach') attachDirectoryRow(type, selected);
  }

  function attachDirectoryRow(type, row) {
    if (!state.returnTo || state.returnTo.type !== type) return;
    if (row.active === false) { showToast('Архивную запись нельзя добавить в документ.', 'warn'); return; }
    const target = state.returnTo;
    const doc = state.documents[target.doc];
    if (target.field === 'works' || target.field === 'parts') {
      if (!doc[target.field].some((item) => item.id === row.id)) doc[target.field].push(target.field === 'parts' ? normalizePart(Object.assign({ quantity: 1 }, clone(row))) : Object.assign({ quantity: 1 }, clone(row)));
    } else if (target.field === 'vehicle') {
      doc.vehicle = [row.brand, row.model, row.plate].filter(Boolean).join(' ');
    } else if (target.field === 'customer' || target.field === 'payer' || target.field === 'client' || target.field === 'counterparty') {
      doc[target.field] = row.name;
    }
    const previous = target.previous || target.doc;
    state.returnTo = null;
    state.activeObject = previous;
    persist();
    render();
    showToast('Позиция добавлена в документ.', 'success');
  }

