  function lineTotal(type, row) {
    const quantity = Number(row.quantity == null ? 1 : row.quantity) || 0;
    const price = Number(row.price || 0);
    return type === 'works' ? quantity * (Number(row.norm || 0)) * price : quantity * price;
  }

  function calculateDocTotal(docType) {
    const doc = state.documents[docType];
    const workTotal = (doc.works || []).reduce((sum, row) => sum + lineTotal('works', row), 0);
    const partTotal = (doc.parts || []).reduce((sum, row) => sum + lineTotal('parts', row), 0);
    return workTotal + partTotal || doc.total || 0;
  }

