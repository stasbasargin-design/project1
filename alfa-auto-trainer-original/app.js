  function handleAction(action) {
    if (state.mode === 'training') {
      const stageItem = currentStage();
      const expected = stageItem.steps[state.step];
      if (!expected || state.completed.has(stageItem.id)) {
        showToast('Этап уже завершён. Перезапустите его или выберите следующий.', 'success');
        return;
      }
      const expectedActions = Array.isArray(expected.action) ? expected.action : [expected.action];
      if (!expectedActions.includes(action)) {
        showToast('Это другой объект формы. Наведите курсор и найдите подсвеченный объект текущего шага.', 'warn');
        return;
      }
      if (action === 'event-conduct') {
        const validation = eventValidationMessage();
        if (validation) { showToast(validation, 'warn'); return; }
      }
      if (action === 'task-complete' && !state.documents.crmTask.called && !String(state.documents.crmTask.result || '').trim()) {
        showToast('Перед завершением выполните звонок из формы или заполните поле «Результат».', 'warn');
        return;
      }
      if (action === 'task-save') {
        const taskError = crmTaskValidationMessage(state.documents.crmTask);
        if (taskError) { showToast(taskError, 'warn'); return; }
      }
      if (action === 'quick-transfer' && !Object.keys(state.documents.quickPick.selected || {}).length) {
        showToast('Сначала выберите хотя бы одну позицию номенклатуры.', 'warn');
        return;
      }
      if (action === 'quick-transfer' && expected.requireStockSplit) {
        const selectedRows = Object.keys(state.documents.quickPick.selected || {}).map((id) => state.directories.parts.find((row) => row.id === id)).filter(Boolean);
        const hasStock = selectedRows.some((row) => Number(row.stock || 0) > 0);
        const hasMissing = selectedRows.some((row) => Number(row.stock || 0) <= 0);
        if (!hasStock || !hasMissing) {
          showToast('Для экзамена выберите две позиции: одну с остатком и одну с нулевым остатком.', 'warn');
          return;
        }
      }
      if (expected.defer) beginTrainingDeferred(expected, action);
      else completeTrainingAction(action);
      return;
    }
    applyLiveAction(action);
  }

  function completeTrainingAction(action) {
    const stageItem = currentStage();
    applyTrainingAction(action);
    state.step += 1;
    if (state.examRun && state.examRun.stageId === stageItem.id) examHistory.completedStep(state.examRun, state.step);
    if (state.step >= stageItem.steps.length) {
      state.completed.add(stageItem.id);
      const result = finishExamAttempt('Завершён');
      persist();
      showToast(result ? `Экзамен «${stageItem.label}» завершён. Оценка: ${result.score}/100.` : `Сценарий «${stageItem.label}» завершён.`, 'success');
    } else {
      showToast('Верно. Переходим к следующему шагу.', 'success');
    }
    render();
  }

  function beginTrainingDeferred(expected, action) {
    if (expected.defer === 'responsibles') { openResponsibles(true); return; }
    if (expected.defer === 'picker') { openTrainingPicker(expected.pickerType, expected.doc, action, expected); return; }
    if (['inline', 'docLine', 'kpStatus', 'kpDataChoice', 'text'].includes(expected.defer)) {
      state.pendingInlineAction = action;
      focusInlineAction(action, expected);
      showToast('Введите или выберите значение прямо в объекте, затем нажмите Tab или Enter.', 'success');
      return;
    }
    if (expected.defer === 'agreementClose') { openAgreementClose(action); return; }
    if (expected.defer === 'expressChoice') { openExpressConfirm(action); return; }
  }

  function focusInlineAction(action, expected = {}) {
    let control = el.screen.querySelector(`.inline-field[data-action="${action}"],.inline-cell[data-action="${action}"],.onec-input[data-action="${action}"]`);
    if (!control && expected.doc && expected.lineType) {
      const rows = state.documents[expected.doc][expected.lineType] || [];
      const index = expected.lineIndex === 'last' ? rows.length - 1 : Number(expected.lineIndex || 0);
      control = el.screen.querySelector(`.inline-cell[data-line-doc="${expected.doc}"][data-line-type="${expected.lineType}"][data-line-index="${index}"][data-line-field="quantity"]`);
    }
    if (control) {
      control.focus();
      if (typeof control.select === 'function' && control.tagName !== 'SELECT') control.select();
    }
  }

