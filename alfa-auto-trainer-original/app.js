  function partStatus(row) {
    const quantity = Number(row.quantity || 0);
    if (Number(row.inProduction || 0) >= quantity && quantity > 0) return { key: 'production', label: 'Передано в производство' };
    if (Number(row.received || 0) > 0) return { key: 'received', label: 'Поступило по заказу' };
    if (Number(row.reserved || 0) > 0 || Number(row.ordered || 0) > 0) return { key: 'reserved', label: 'Заказано / в резерве' };
    if (Number(row.stock || 0) >= quantity && quantity > 0) return { key: 'stock', label: 'Есть на складе' };
    return { key: 'missing', label: 'Требуется заказать' };
  }

